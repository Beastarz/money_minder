import 'package:money_minder/models/account.dart';
import 'package:money_minder/models/category.dart';
import 'package:money_minder/models/currency.dart';

enum TransactionType {
  expense,
  income,
  transfer
}

class Transaction {
  final int id;
  late final DateTime date;
  final TransactionType type;
  final Account fromAccount;
  final Account? toAccount;
  final Category? toCategory;
  final double amount;
  final Currency currency;
  final Currency mainCurrency;
  final String note;

  Transaction({
    required this.id,
    required DateTime date,
    required this.type,
    required this.fromAccount,
    required this.toAccount,
    required this.toCategory,
    required this.amount,
    required this.currency,
    required this.mainCurrency,
    required this.note,
  }) {
    this.date = DateTime(date.year, date.month, date.day);
  }

  get mainAmount => Currency.convert(currency, mainCurrency, amount);

  /// use this to convert map to transaction
  factory Transaction.fromMap(Map<String, dynamic> map, Account fromAccount, Account? toAccount, Category? category, Currency mainCurrency) {
    return Transaction(
      id: map['id'],
      date: DateTime.parse(map['date']),
      type: map['type'] == 'expense'
          ? TransactionType.expense
          : map['type'] == 'transfer'
          ? TransactionType.transfer
          : TransactionType.income,
      fromAccount: fromAccount,
      toAccount: toAccount,
      toCategory: category,
      amount: map['amount'],
      currency: Currency.of(map['currency']),
      mainCurrency: mainCurrency,
      note: map['note'],
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'date': date.toIso8601String(),
      'type': type.name,
      'from_account_id': fromAccount.id,
      'to_account_id': toAccount?.id,
      'to_category_id': toCategory?.id,
      'amount': amount,
      'currency': currency
          .currency()
          .name,
      'note': note,
    };
  }

  static Map<String, dynamic> insertAsMap({
    required DateTime date,
    required TransactionType type,
    required int fromAccountId,
    int? toAccountId,
    int? toCategoryId,
    required double amount,
    required Currency currency,
    required String note,
  }) {
    if (toAccountId == null && toCategoryId == null) {
      throw Exception('toAccountId and toCategoryId cannot be null at the same time');
    }
    DateTime d = DateTime(date.year, date.month, date.day);

    return {
      'date': d.toIso8601String(),
      'type': type.name,
      'from_account_id': fromAccountId,
      'to_account_id': toAccountId,
      'to_category_id': toCategoryId,
      'amount': amount,
      'currency': currency
          .currency()
          .name,
      'note': note,
    };
  }

  static Map<String, dynamic> insertAsRawMap(
      {
        required String date,
        required String type,
        required int fromAccountId,
        int? toAccountId,
        int? toCategoryId,
        required double amount,
        required String currency,
        required String note,
      }) {
    return {
      'date': date,
      'type': type,
      'from_account_id': fromAccountId,
      'to_account_id': toAccountId,
      'to_category_id': toCategoryId,
      'amount': amount,
      'currency': currency,
      'note': note,
    };
  }

  Transaction copyWith({
    DateTime? date,
    Account? fromAccount,
    Account? toAccount,
    Category? toCategory,
    double? amount,
    Currency? currency,
    String? note,
  }) {
    return Transaction(
        id: id,
        date: date ?? this.date,
        type: type,
        fromAccount: fromAccount ?? this.fromAccount,
        toAccount: toAccount ?? this.toAccount,
        toCategory: toCategory ?? this.toCategory,
        amount: amount ?? this.amount,
        currency: currency ?? this.currency,
        mainCurrency: mainCurrency,
        note: note ?? this.note,
    );
  }

  /// use this to group transactions by date
  /// startDates should be generated by DateFilter class
  static List<List<Transaction>> groupTransactionsByDate(List<Transaction> transactions, List<DateTime> startDates) {
    List<List<Transaction>> groupedTransactions = [];
    for (int i = 0; i < startDates.length-1 ; i++) {
      groupedTransactions.add(
          transactions.where(
                  (transaction) =>
                  (transaction.date.isAfter(startDates[i]) || transaction.date.isAtSameMomentAs(startDates[i]))
                          && transaction.date.isBefore(startDates[i+1])
          ).toList());
    }
    return groupedTransactions;
  }

  /// temp
  @override
  String toString() {
    return 'from: ${fromAccount.name} ${amount.toStringAsFixed(2)} ${toAccount == null ? 'null' : toAccount!.name}';
  }

}